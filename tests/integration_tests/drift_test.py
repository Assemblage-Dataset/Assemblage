"""Schema drift gate.

Proves the SQLModel ORM (assemblage.db.models) still describes exactly
what the Alembic migrations produce, so no future `alembic revision
--autogenerate` can silently propose a destructive change and the models stay
frozen to the live database (backend/alembic/README.md).

Runs against a freshly-created, throwaway database on the same server as
TEST_DB_ADDR — never the seeded scratch db, so it is order-independent.
"""

import contextlib
import os

import pytest
import sqlalchemy as sqla
from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected
from sqlmodel import SQLModel

from tests.constants import TEST_DB_ADDR

from .conftest import alembic_config_for

pytestmark = pytest.mark.integration

# The five ORM-managed tables (alembic_version is Alembic's own bookkeeping).
_MODEL_TABLES = {"buildopt", "b_status", "binaries", "projects", "scrapers"}


@contextlib.contextmanager
def _empty_database():
    """Create a uniquely-named empty database on the test server, drop it after."""
    base = sqla.engine.make_url(TEST_DB_ADDR)
    scratch_name = f"assemblage_drift_{os.getpid()}"
    admin = base.set(database="postgres")
    admin_engine = sqla.create_engine(admin, isolation_level="AUTOCOMMIT")
    with admin_engine.connect() as conn:
        conn.execute(sqla.text(f'DROP DATABASE IF EXISTS "{scratch_name}"'))
        conn.execute(sqla.text(f'CREATE DATABASE "{scratch_name}"'))
    try:
        yield base.set(database=scratch_name)
    finally:
        with admin_engine.connect() as conn:
            conn.execute(
                sqla.text(
                    "SELECT pg_terminate_backend(pid) FROM pg_stat_activity "
                    "WHERE datname = :n AND pid <> pg_backend_pid()"
                ),
                {"n": scratch_name},
            )
            conn.execute(sqla.text(f'DROP DATABASE IF EXISTS "{scratch_name}"'))
        admin_engine.dispose()


def test_migrations_match_models_and_reflect_clean():
    with _empty_database() as scratch_url:
        # render_as_string(hide_password=False): plain str(url) masks the
        # password to '***', which psycopg2 would then try to authenticate with.
        config = alembic_config_for(scratch_url.render_as_string(hide_password=False))

        # (a) migrate the empty database to head
        command.upgrade(config, "head")

        # (b) autogenerate must find NO difference between models and the DB.
        # command.check raises AutogenerateDiffsDetected when anything drifts.
        try:
            command.check(config)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            pytest.fail(f"alembic check detected schema drift:\n{exc}", pytrace=False)

        # (c) reflect information_schema and compare names + nullability against
        #     the SQLModel metadata for every ORM-managed table.
        engine = sqla.create_engine(scratch_url)
        try:
            inspector = sqla.inspect(engine)
            reflected_tables = set(inspector.get_table_names())
            assert _MODEL_TABLES <= reflected_tables, (
                f"missing tables: {_MODEL_TABLES - reflected_tables}"
            )

            for table_name in _MODEL_TABLES:
                model_table = SQLModel.metadata.tables[table_name]
                model_cols = {c.name: bool(c.nullable) for c in model_table.columns}
                reflected_cols = {
                    c["name"]: bool(c["nullable"]) for c in inspector.get_columns(table_name)
                }
                assert model_cols.keys() == reflected_cols.keys(), (
                    f"{table_name}: column-name mismatch "
                    f"model-only={model_cols.keys() - reflected_cols.keys()} "
                    f"db-only={reflected_cols.keys() - model_cols.keys()}"
                )
                for col, model_nullable in model_cols.items():
                    assert model_nullable == reflected_cols[col], (
                        f"{table_name}.{col}: nullability model={model_nullable} "
                        f"db={reflected_cols[col]}"
                    )
        finally:
            engine.dispose()
